--  DDL for View V_EMPLOYEES
--------------------------------------------------------

  CREATE OR REPLACE FORCE NONEDITIONABLE VIEW "SYSTEM"."V_EMPLOYEES" ("MITARBEITER_ID", "MITARBEITER", "GEHALT", "AVG_GEHALT_BY_ABTEILUNG", "GEHALT_GREATER_THAN_AVG", "EINTRITT", "MONTHS_BELONGING", "ABTEILUNG", "CHEF_NAME") AS 
  (select m.mitarb_id as mitarbeiter_id,
       m.vorname
       || ' '
       || upper(m.nachname) as mitarbeiter,
       m.gehalt,
       round(
          avg(m.gehalt)
          over(partition by m.abt_id),
          2
       ) as avg_gehalt_by_abteilung,
        case when m.gehalt > round(
          avg(m.gehalt)
          over(partition by m.abt_id),
          2
       ) then true else false end as gehalt_greater_than_avg,
       m.eintritt,
       trunc(months_between(
          sysdate,
          m.eintritt
       )) as months_belonging,
       a.name as abteilung,
       c.nachname as chef_name
  from mitarbeiter m
  left join abteilungen a
on m.abt_id = a.abt_id
  left join mitarbeiter c
on c.mitarb_id = m.chef_id)
order by mitarbeiter_id
;
